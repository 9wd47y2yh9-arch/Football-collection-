# Ensure every existing player in base_part has status and isCardEligible
# Find each player closing: priceHistory: [ ... ]\n  },
# We can replace priceHistory: [\n ... \n    ],\n  }, with priceHistory: [ ... ],\n    status: 'active',\n    isCardEligible: true,\n  },
def add_status_to_block(text):
    pattern = r'(priceHistory:\s*\[[\s\S]*?\])(,?\s*\n\s*\})'
    def repl(m):
        content = m.group(1)
        suffix = m.group(2)
        if 'status:' not in content:
            return content + ",\n    status: 'active',\n    isCardEligible: true" + suffix
        return m.group(0)
    return re.sub(pattern, repl, text)

