type TranslationKey = keyof typeof TRANSLATIONS['ja'];

const getInitialLang = (): SupportedLanguage => {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('fc_lang') as SupportedLanguage;
    if (saved === 'ja' || saved === 'en' || saved === 'es') return saved;
  }
  return 'ja';
};

let currentLang: SupportedLanguage = getInitialLang();
const listeners = new Set<(lang: SupportedLanguage) => void>();

export function setAppLanguage(lang: SupportedLanguage) {
  currentLang = lang;
  if (typeof localStorage !== 'undefined') {
    try {
      localStorage.setItem('fc_lang', lang);
    } catch {
      // storage unavailable
    }
  }
  listeners.forEach((fn) => fn(lang));
}

export function getAppLanguage(): SupportedLanguage {
  return currentLang;
}

export function t(key: TranslationKey, lang?: SupportedLanguage): string {
  const l = lang || currentLang;
  const dict = TRANSLATIONS[l] || TRANSLATIONS.ja;
  return dict[key] || TRANSLATIONS.ja[key] || key;
}

export function useI18n() {
  const [lang, setLang] = useState<SupportedLanguage>(currentLang);

  useEffect(() => {
    const handler = (newLang: SupportedLanguage) => setLang(newLang);
    listeners.add(handler);
    return () => {
      listeners.delete(handler);
    };
  }, []);

  return {
    lang,
    currentLanguage: lang,
    setLang: setAppLanguage,
    setLanguage: setAppLanguage,
    t: (key: TranslationKey) => t(key, lang),
  };
}
